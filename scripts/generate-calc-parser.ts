/** Java-free parser generation. Checked-in output makes unchanged builds cheap/offline. */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import pkg from "../package.json";
import evalsPkg from "../packages/evals/package.json";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const BASE = "packages/evals/src/validator";
const FILES = ["TableauCalculationGrammarLexer.ts", "TableauCalculationGrammarParser.ts"] as const;
const hash = (data: string | Buffer) => createHash("sha256").update(data).digest("hex");

interface Manifest { input: string; outputs: Record<string, string> }

export async function generateCalcParser(options: { root?: string; force?: boolean; check?: boolean } = {}): Promise<boolean> {
  const root = options.root ?? ROOT;
  const grammar = join(root, BASE, "grammar/TableauCalculationGrammar.g4");
  const output = join(root, BASE, "generated");
  const manifestPath = join(output, "manifest.json");
  // Include generation/postprocessing code and the exact generator/runtime pins.
  const input = hash(Buffer.concat([
    readFileSync(grammar), readFileSync(fileURLToPath(import.meta.url)),
    Buffer.from(JSON.stringify([pkg.devDependencies["antlr-ng"], evalsPkg.dependencies.antlr4ng])),
  ]));
  let manifest: Manifest | undefined;
  try { manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as Manifest; } catch { /* missing/invalid cache */ }
  const fresh = manifest?.input === input && FILES.every((name) =>
    existsSync(join(output, name)) && manifest?.outputs[name] === hash(readFileSync(join(output, name))));
  if (options.check) {
    if (!fresh) throw new Error("Calculation parser cache is stale. Run `bun generate:calc` and commit the generated files.");
    return false;
  }
  if (fresh && !options.force) return false;

  const temp = mkdtempSync(join(tmpdir(), "tableau-ai-eval-calc-parser-"));
  try {
    const runner = join(dirname(fileURLToPath(import.meta.resolve("antlr-ng"))), "../cli/runner.js");
    const start = performance.now();
    const proc = Bun.spawn([process.execPath, runner, "-Dlanguage=TypeScript", "-l", "false",
      "--exact-output-dir", "-o", temp, grammar], { stdout: "inherit", stderr: "inherit" });
    if (await proc.exited !== 0) throw new Error("antlr-ng calculation parser generation failed");
    const outputs: Record<string, string> = {};
    const contents = FILES.map((name) => {
      // Generator templates contain unused variables; keep strict checking on handwritten code.
      const text = "// @ts-nocheck — generated by scripts/generate-calc-parser.ts; do not edit.\n"
        + readFileSync(join(temp, name), "utf8").replaceAll(grammar, "TableauCalculationGrammar.g4")
          .replace(/(from\s+["'][^"']+)\.js(["'])/g, "$1.ts$2");
      outputs[name] = hash(text);
      return text;
    });
    mkdirSync(output, { recursive: true });
    FILES.forEach((name, i) => writeFileSync(join(output, name), contents[i]!));
    writeFileSync(manifestPath, JSON.stringify({ input, outputs }, null, 2) + "\n");
    console.log(`Generated calculation lexer/parser in ${Math.round(performance.now() - start)} ms (no Java).`);
    return true;
  } finally {
    rmSync(temp, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== "--force" && arg !== "--check")) throw new Error("Usage: bun generate:calc [--force | --check]");
  await generateCalcParser({ force: args.includes("--force"), check: args.includes("--check") });
}
